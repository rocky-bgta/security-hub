    /**
     * Get a list of coupons with pagination and filtering
     *
     * @param offset
     * @param limit
     * @param searchParam
     * @param isActive
     * @param isExpired
     * @return
     * @author Mahadi Hasan Joy
     * @since 2025-04-17
     */
    @Override
    public List<CouponCreateResponseDTO> getCoupons(int offset, int limit, String searchParam, Boolean isActive,
            Boolean isExpired, String couponType, String productId, String order) {
        if (limit <= 0) {
            throw new BillingServiceException(
                "Limit must be greater than 0",
                HttpStatus.BAD_REQUEST
            );
        }

        if (offset < 0) {
            throw new BillingServiceException(
                "Offset must be greater than or equal to 0",
                HttpStatus.BAD_REQUEST
            );
        }

        int skip = offset * limit;
        Criteria criteria = buildCouponListCriteria(searchParam, isActive, isExpired, couponType, productId);
        Query query = new Query(criteria)
                .with(Sort.by(resolveCreatedAtSortDirection(order), "createdAt"))
                .skip(skip)
                .limit(limit);
        List<Coupon> couponList = mongoTemplate.find(query, Coupon.class);

        if (couponList.isEmpty()) {
            return List.of();
        }

        return couponList.stream().map(this::mapToResponse).collect(Collectors.toList());
    }


    /**
     * Get the count of coupons based on search parameters
     *
     * @param searchParam
     * @param isActive
     * @param isExpired
     * @return
     * @author Mahadi Hasan Joy
     * @since 2025-04-17
     */
    @Override
    public long getCouponsCount(String searchParam, Boolean isActive, Boolean isExpired, String couponType, String productId) {
        Criteria criteria = buildCouponListCriteria(searchParam, isActive, isExpired, couponType, productId);
        Query query = new Query(criteria);
        return mongoTemplate.count(query, Coupon.class);
    }

    private Criteria buildCouponListCriteria(String searchParam, Boolean isActive, Boolean isExpired,
            String couponType, String productId) {
        Criteria criteria = new Criteria();
        List<Criteria> criteriaList = new ArrayList<>();

        if (searchParam != null && !searchParam.trim().isEmpty()) {
            criteriaList.add(Criteria.where("code").regex(searchParam.trim(), "i"));
        }

        if (isActive != null) {
            criteriaList.add(Criteria.where("isActive").is(isActive));
        }

        if (isExpired != null) {
            Instant now = Instant.now();
            if (isExpired) {
                criteriaList.add(Criteria.where("validUntil").lt(now));
            } else {
                criteriaList.add(Criteria.where("validUntil").gte(now));
            }
        }

        if (couponType != null && !couponType.trim().isEmpty()) {
            try {
                CouponType type = CouponType.valueOf(couponType.trim().toUpperCase());
                criteriaList.add(Criteria.where("type").is(type));
            } catch (IllegalArgumentException e) {
                throw new BillingServiceException(
                    "Invalid coupon type: " + couponType + ". Valid values are: PERCENTAGE, FIXED",
                    HttpStatus.BAD_REQUEST
                );
            }
        }

        if (productId != null && !productId.trim().isEmpty()) {
            criteriaList.add(Criteria.where("productRestrictions.productId").is(productId.trim()));
        }

        if (!criteriaList.isEmpty()) {
            criteria.andOperator(criteriaList.toArray(new Criteria[0]));
        }

        return criteria;
    }

    private Sort.Direction resolveCreatedAtSortDirection(String order) {
        if (order == null || order.isBlank()) {
            return Sort.Direction.ASC;
        }
        return switch (order.trim().toUpperCase()) {
            case "ASC" -> Sort.Direction.ASC;
            case "DESC" -> Sort.Direction.DESC;
            default -> throw new BillingServiceException(
                    "Invalid order: " + order + ". Valid values are: ASC, DESC",
                    HttpStatus.BAD_REQUEST);
        };
    }


    /**
     * Update an existing coupon
     *
     * @param id
     * @param dto
     * @return
     * @author Mahadi Hasan Joy
     * @since 2025-04-17
     */
    @Override
    public CouponCreateResponseDTO updateCoupon(String id, CouponCreateRequestDTO dto) {
        Coupon coupon = couponRepository.findById(id).orElseThrow(() -> new CouponNotFoundException("Coupon not found with ID: " + id));

        // Only update fields if provided in DTO, otherwise keep existing values from repository
        
        // Update name if provided
        if (dto.getName() != null && !dto.getName().isBlank()) {
            coupon.setName(dto.getName());
        }
        
        // Update description if provided
        if (dto.getDescription() != null && !dto.getDescription().isBlank()) {
            coupon.setDescription(dto.getDescription());
        }
        
        // Update code if provided (and check for duplicates)
        if (dto.getCode() != null && !dto.getCode().isBlank()) {
            // Check if another coupon already has the same code
            Optional<Coupon> existingWithSameCode = couponRepository.findByCode(dto.getCode());
            if (existingWithSameCode.isPresent() && !existingWithSameCode.get().getId().equals(id)) {
                throw new CouponAlreadyExistsException("Another coupon already exists with code: " + dto.getCode());
            }
            coupon.setCode(dto.getCode());
        }
        
        // Update autoGenerated if provided (boolean always has a value, so update it)
        coupon.setAutoGenerated(dto.isAutoGenerated());
        
        // Update type if provided
        if (dto.getType() != null && !dto.getType().isBlank()) {
            try {
                coupon.setType(CouponType.valueOf(dto.getType().toUpperCase()));
            } catch (IllegalArgumentException e) {
                throw new UnsupportedCouponTypeException("Invalid coupon type: " + dto.getType());
            }
        }
        
        // Update value if provided
        if (dto.getValue() != null) {
            coupon.setValue(dto.getValue());
        }
        
        // Update currency if provided (can be null to clear it)
        if (dto.getCurrency() != null) {
            coupon.setCurrency(dto.getCurrency());
        }
        
        // Update validFrom if provided
        if (dto.getValidFrom() != null) {
            coupon.setValidFrom(dto.getValidFrom());
        }
        
        // Update validUntil if provided
        if (dto.getValidUntil() != null) {
            coupon.setValidUntil(dto.getValidUntil());
        }
        
        // Update usageLimit if provided
        if (dto.getUsageLimit() != null) {
            coupon.setUsageLimit(dto.getUsageLimit());
        }
        
        // Update minPurchaseAmount if provided (can be null to clear it)
        if (dto.getMinPurchaseAmount() != null) {
            coupon.setMinPurchaseAmount(dto.getMinPurchaseAmount());
        }
        
        // Update isActive (boolean always has a value, so update it)
        coupon.setActive(dto.isActive());
        
        // Update isStackable (boolean always has a value, so update it)
        coupon.setStackable(dto.isStackable());
        
        // Update geographicRestrictions if provided (can be null or empty list)
        if (dto.getGeographicRestrictions() != null) {
            coupon.setGeographicRestrictions(dto.getGeographicRestrictions());
        }
        
        // Update productRestrictions: if provided (even if empty list), update it; if null, keep existing value
        if (dto.getProductRestrictions() != null) {
            // Allow empty list to clear restrictions, or set new restrictions
            List<ProductRestriction> restrictions = dto.getProductRestrictions().isEmpty() 
                ? null 
                : dto.getProductRestrictions().stream().map(this::mapToModel).collect(Collectors.toList());
            coupon.setProductRestrictions(restrictions);
        }
        // If dto.getProductRestrictions() is null, don't change existing productRestrictions (partial update)
        
        coupon.setUpdatedAt(Instant.now());

        return mapToResponse(couponRepository.save(coupon));
    }


