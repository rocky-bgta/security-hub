    /**
     * Create a new coupon
     *
     * @author Mahadi Hasan Joy
     * @since 2025-04-15
     */
    @Override
    public CouponCreateResponseDTO createCoupon(CouponCreateRequestDTO couponCreateRequestDTO) {

        if (couponRepository.existsByCode(couponCreateRequestDTO.getCode())) {
            throw new CouponAlreadyExistsException("Coupon code already exists: " + couponCreateRequestDTO.getCode());
        }

        CouponType couponType = CouponType.valueOf(couponCreateRequestDTO.getType().toUpperCase());

        Coupon coupon = new Coupon();
        coupon.setName(couponCreateRequestDTO.getName());
        coupon.setDescription(couponCreateRequestDTO.getDescription());
        coupon.setCode(couponCreateRequestDTO.getCode());
        coupon.setAutoGenerated(couponCreateRequestDTO.isAutoGenerated());
        coupon.setType(couponType);
        coupon.setValue(couponCreateRequestDTO.getValue());
        coupon.setCurrency(couponCreateRequestDTO.getCurrency());
        coupon.setValidFrom(couponCreateRequestDTO.getValidFrom());
        coupon.setValidUntil(couponCreateRequestDTO.getValidUntil());
        coupon.setUsageLimit(couponCreateRequestDTO.getUsageLimit());
        coupon.setTotalUsed(0);
        coupon.setMinPurchaseAmount(couponCreateRequestDTO.getMinPurchaseAmount());
        coupon.setActive(couponCreateRequestDTO.isActive());
        coupon.setStackable(couponCreateRequestDTO.isStackable());
        coupon.setGeographicRestrictions(couponCreateRequestDTO.getGeographicRestrictions());

        // Set productRestrictions: if provided and not empty, map and set; if null or empty, set to null
        if (couponCreateRequestDTO.getProductRestrictions() != null && !couponCreateRequestDTO.getProductRestrictions().isEmpty()) {
            List<ProductRestriction> restrictions = couponCreateRequestDTO.getProductRestrictions().stream().map(this::mapToModel).collect(Collectors.toList());
            coupon.setProductRestrictions(restrictions);
        } else {
            // Allow creating coupon without productRestrictions (null or empty list)
            coupon.setProductRestrictions(null);
        }

        coupon.setCreatedAt(Instant.now());
        coupon.setUpdatedAt(Instant.now());

        Coupon saved = couponRepository.save(coupon);
        return mapToResponse(saved);
    }


