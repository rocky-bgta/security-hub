    /**
     * Calculate the normal bill without any coupon
     *
     * @param packageItems List of product selections
     * @return CouponDiscountResponseDTO
     * @author Mahadi Hasan Joy
     * @since 2025-04-20
     */
    @Override
    public CouponDiscountResponseDTO calculateNormalBill(List<ProductSelectionDto> packageItems) {
        if (packageItems == null || packageItems.isEmpty()) {
            throw new IllegalArgumentException("Package items are required for bill calculation.");
        }

        double actualTotal = 0.0;
        double totalDiscount = 0.0;
        List<DiscountedItemDTO> breakdown = new ArrayList<>();

        for (ProductSelectionDto item : packageItems) {
            double price = MoneyUtil.round(item.getPricePerLicense() * item.getLicenseCount() * item.getValidityPeriod());
            actualTotal = MoneyUtil.round(actualTotal + price);

            // No coupon: original == discounted, no discount applied
            breakdown.add(new DiscountedItemDTO(item.getProductId(), price, price, false));
        }

        double subtotal = actualTotal;

        return new CouponDiscountResponseDTO(
                actualTotal,
                totalDiscount,
                subtotal,
                0.0,            // VAT excluded from here
                subtotal,       // Grand total same as subtotal (no VAT included)
                breakdown
        );
    }


