    /**
     * Validate a coupon based on various criteria
     *
     * @param dto
     * @return
     * @author Mahadi Hasan Joy
     * @since 2025-04-20
     */
    @Override
    public CouponCreateResponseDTO validateCoupon(ValidateCouponRequestDTO dto) {
        if ((dto.getCouponId() == null || dto.getCouponId().isBlank()) &&
                (dto.getCouponCode() == null || dto.getCouponCode().isBlank())) {
            throw new CouponValidationException("Either coupon ID or coupon code must be provided.");
        }

        if (dto.getAmount() == null) {
            throw new CouponValidationException("Amount is required for validation.");
        }

        String code = dto.getCouponCode();
        if (code == null || code.isBlank()) {
            Coupon coupon = couponRepository.findById(dto.getCouponId())
                    .orElseThrow(() -> new CouponNotFoundException("Coupon not found with ID: " + dto.getCouponId()));
            code = coupon.getCode();
        }

        return validateForRedemption(
                code,
                dto.getAmount(),
                dto.getPackageItems(),
                dto.getClientCountryId()
        );
    }

    @Override
    public CouponCreateResponseDTO validateForRedemption(String couponCode, double amount,
            List<ProductSelectionDto> packageItems, String clientCountryId) {
        Coupon coupon = loadCouponByCode(couponCode);
        validateCouponForRedemption(coupon, amount, packageItems, clientCountryId);
        return mapToResponse(coupon);
    }

