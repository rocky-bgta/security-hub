    @Override
    public void releaseCouponUsage(String couponId) {
        if (couponId == null || couponId.isBlank()) {
            return;
        }
        Optional<Coupon> released = couponRepositoryCustom.decrementUsageIfAboveZero(couponId);
        if (released.isEmpty()) {
            log.warn("Coupon usage release skipped: totalUsed already 0 for coupon ID: {}", couponId);
        }
    }

    private void validateCouponAvailability(Coupon coupon) {
        if (!coupon.isActive()) {
            throw new CouponValidationException("Coupon is not active.");
        }

        Instant now = Instant.now();
        if (coupon.getValidFrom() != null && coupon.getValidFrom().isAfter(now)) {
            throw new CouponValidationException(
                    String.format("Coupon is not yet valid. Valid from: %s. Current time: %s",
                            coupon.getValidFrom(), now));
        }

        if (coupon.getValidUntil() != null && coupon.getValidUntil().isBefore(now)) {
            throw new CouponValidationException(
                    String.format("%s Coupon has expired", coupon.getCode()));
        }

        int used = coupon.getTotalUsed() != null ? coupon.getTotalUsed() : 0;
        if (coupon.getUsageLimit() != null && used >= coupon.getUsageLimit()) {
            throw new CouponValidationException("Coupon usage limit has been reached.");
        }
    }

    private void validateCouponForRedemption(Coupon coupon, double amount,
            List<ProductSelectionDto> packageItems, String clientCountryId) {
        validateCouponAvailability(coupon);

        if (coupon.getMinPurchaseAmount() != null && amount < coupon.getMinPurchaseAmount()) {
            throw new CouponValidationException("Minimum purchase amount not met for this coupon.");
        }

        if (coupon.getGeographicRestrictions() != null && !coupon.getGeographicRestrictions().isEmpty()) {
            if (clientCountryId == null || !coupon.getGeographicRestrictions().contains(clientCountryId)) {
                throw new CouponValidationException("Coupon is not valid in your region.");
            }
            return;
        }

        if (packageItems != null && !packageItems.isEmpty()
                && coupon.getProductRestrictions() != null && !coupon.getProductRestrictions().isEmpty()) {
            boolean anyMatch = coupon.getProductRestrictions().stream()
                    .anyMatch(restriction -> packageItems.stream()
                            .anyMatch(pkg -> {
                                boolean productMatch = pkg.getProductId().equals(restriction.getProductId());
                                if (restriction.getPackageId() == null || restriction.getPackageId().isBlank()) {
                                    return productMatch;
                                }
                                return productMatch
                                        && pkg.getPackageId() != null
                                        && pkg.getPackageId().equals(restriction.getPackageId());
                            }));

            if (!anyMatch) {
                throw new CouponValidationException("Coupon is not valid for any of the selected products/packages.");
            }
        }
    }

    /**
     * Calculate the discount based on the coupon and package items
     * 
     * @param packageItems List of product selections
     * @param clientCountryId Client country ID (UUID format)
     * @param coupon Coupon to apply
     * @return CouponDiscountResponseDTO
     * @author Mahadi Hasan Joy
     * @since 2025-04-20
     */
    @Override
    public CouponDiscountResponseDTO calculateCouponDiscount(List<ProductSelectionDto> packageItems, String clientCountryId, CouponCreateResponseDTO coupon) {
        if (packageItems == null || coupon == null) {
            throw new IllegalArgumentException("Package items and coupon are required for discount calculation.");
        }

        boolean applyDiscountToAll = false;

        if (coupon.getGeographicRestrictions() != null && !coupon.getGeographicRestrictions().isEmpty()) {
            if (clientCountryId != null && coupon.getGeographicRestrictions().contains(clientCountryId)) {
                applyDiscountToAll = true;
            }
        }

        List<String> eligibleProductIds = coupon.getProductRestrictions() != null
                ? coupon.getProductRestrictions().stream().map(ProductRestrictionDTO::getProductId).collect(Collectors.toList())
                : null;

        if (!applyDiscountToAll && (eligibleProductIds == null || eligibleProductIds.isEmpty()) &&
                (coupon.getGeographicRestrictions() == null || coupon.getGeographicRestrictions().isEmpty())) {
            applyDiscountToAll = true;
        }

        double actualTotal = 0.0;
        double totalDiscount = 0.0;
        List<DiscountedItemDTO> breakdown = new ArrayList<>();

        for (ProductSelectionDto item : packageItems) {
            double original = MoneyUtil.round(item.getLicenseCount() * item.getPricePerLicense() * item.getValidityPeriod());
            double discounted = original;
            boolean applied = false;

            // Check eligibility: must match a product/package restriction (same rules as validateForRedemption)
            boolean isEligible = false;
            if (applyDiscountToAll) {
                isEligible = true;
            } else if (coupon.getProductRestrictions() != null && !coupon.getProductRestrictions().isEmpty()) {
                isEligible = coupon.getProductRestrictions().stream()
                        .anyMatch(restriction -> lineItemMatchesProductRestriction(item, restriction));
            }

            if (isEligible) {
                if ("PERCENTAGE".equalsIgnoreCase(coupon.getType())) {
                    discounted = MoneyUtil.round(original - (original * coupon.getValue() / 100.0));
                } else if ("FIXED".equalsIgnoreCase(coupon.getType())) {
                    discounted = MoneyUtil.round(Math.max(0, original - coupon.getValue()));
                }
                totalDiscount = MoneyUtil.round(totalDiscount + (original - discounted));
                applied = true;
            }

            actualTotal = MoneyUtil.round(actualTotal + original);
            breakdown.add(new DiscountedItemDTO(item.getProductId(), original, discounted, applied));
        }

        double subtotal = MoneyUtil.round(actualTotal - totalDiscount);

        return new CouponDiscountResponseDTO(
                actualTotal,
                totalDiscount,
                subtotal,
                0.0,               // VAT excluded
                subtotal,          // Grand total equals subtotal
                breakdown
        );
    }

    private boolean lineItemMatchesProductRestriction(ProductSelectionDto item, ProductRestrictionDTO restriction) {
        if (restriction.getProductId() == null || !restriction.getProductId().equals(item.getProductId())) {
            return false;
        }
        if (restriction.getPackageId() == null || restriction.getPackageId().isBlank()) {
            return true;
        }
        return restriction.getPackageId().equals(item.getPackageId());
    }



